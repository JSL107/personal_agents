// 조사만 허용해 "아까운" 같은 일반 낱말을 대화 참조로 오인하지 않는다.
// 접속어(그러면·그럼·그래서)와 지시어(이거·이걸·그걸)도 넣는다 — 실제 대화는 "그러면 내가 고칠 수 있게
// 일정 등록해줄래?" 처럼 앞 대화를 받는데, 빠져 있으면 문장 조각이 제목으로 등록된다(2026-10-30 실제 DM).
const REFERENCE =
  /(?:^|[^가-힣])(원인|그거|그것|그걸|이거|이것|이걸|방금|위\s*내용|분석한|아까|그러면|그럼|그래서)(?=$|[^가-힣]|(?:과|와|을|를|이|가|은|는|에|에서|으로|로|도|만|의|랑|하고)(?=$|[^가-힣]))/;

export const refersToPriorConversation = (text: string): boolean =>
  REFERENCE.test(text);

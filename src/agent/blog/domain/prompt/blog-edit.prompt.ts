// 본문 절반이 사라지는 것은 "정리" 가 아니라 사고다.
//
// **프롬프트와 가드가 같은 상수를 읽는다.** 이 값이 코드에만 있던 동안 모델은 예산을 모른 채
// 자르고 코드는 자른 뒤에 벌했다 — 실측 4회 중 3회가 53~59% 로 끊겼고, 통과한 1회도 60.45%
// 로 임계선에 걸쳐 있었다. 통과·차단이 품질이 아니라 회차 노이즈로 갈린다는 뜻이다.
// 두 자리가 갈리지 않게 한 곳에 둔다.

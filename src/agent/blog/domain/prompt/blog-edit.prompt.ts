export const buildBlogEditPrompt = (input: {
  title: string;
  category: string;
  tags: string[];
  summary: string;
  markdown: string;
}): string =>
  [
    '[초안 메타데이터]',
    `제목: ${input.title}`,
    `카테고리: ${input.category}`,
    `태그: ${input.tags.join(', ')}`,
    `요약: ${input.summary}`,
    '',
    '[익명화된 본문 Markdown]',
    input.markdown,
  ].join('\n');

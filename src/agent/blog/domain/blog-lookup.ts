// 블로그 발행 여부·초안 목록을 묻는 조회 문장 판별 — 발행 절차보다 먼저 본다.
//
// 발행 워커는 원문에서 제목 일부만 뽑아 바로 발행 절차(초안 익명화 LLM·승인 카드)를 시작한다. 그래서
// 물음표 없는 "남은 초안 알려줘" 도 발행 카드를 만든다. 조회 문장이면 발행하지 않고 기록으로 답한다.
// 명시적 발행 지시("발행해줘", "올려줘", "게시해줘")가 있으면 조회가 아니다.

const LOOKUP_PATTERNS: readonly RegExp[] = [
  // "발행됐어", "발행 됐나", "게시됐어", "올라갔어"
  /(?:발행|게시)\s*(?:됐|되었|된|됬|했|한)|올라갔/,
  // "남은 초안 뭐 있어", "초안 목록 보여줘", "글 뭐 남았어"
  /(?:초안|글).{0,10}(?:뭐|무엇|목록|알려|보여|있어|있나|남았|몇)/,
];

const PUBLISH_INTENT =
  /(?:발행|게시|업로드)\s*(?:해|해줘|해줄래|하자|해주세요)|올려\s*(?:줘|줄래|주세요)?/;

export const isBlogLookup = (text: string): boolean =>
  !PUBLISH_INTENT.test(text) &&
  LOOKUP_PATTERNS.some((pattern) => pattern.test(text));

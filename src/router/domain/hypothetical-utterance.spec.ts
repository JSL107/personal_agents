describe('findHypotheticalMarker', () => {
  describe.each(Object.entries(HYPOTHETICAL))('%s 질문·가정형', (_, texts) => {
    it.each(texts)('"%s" 는 표지가 걸린다', (text) => {
      expect(findHypotheticalMarker(text)).not.toBeNull();
    });
  });

  describe.each(Object.entries(DECLARATIVE))(
    '%s 평서 지시(대조군)',
    (_, texts) => {
      it.each(texts)('"%s" 는 표지가 걸리지 않는다', (text) => {
        expect(findHypotheticalMarker(text)).toBeNull();
      });
    },
  );

  it('Slack 멘션이 앞에 붙어도 판정은 같다', () => {
    expect(
      findHypotheticalMarker('<@U0AULUXLF9B> 8일 기준이라면 4일 남아?'),
    ).not.toBeNull();
    expect(
      findHypotheticalMarker('<@U0AULUXLF9B> 내일 휴가 등록해줘'),
    ).toBeNull();
  });

  it('라면(음식)이 문장 중간 낱말 일부면 걸리지 않는다', () => {
    expect(findHypotheticalMarker('라면땡기는날 휴가 등록해줘')).toBeNull();
  });
});

describe('formatHeldWrite', () => {
  it('하지 않은 일과 실제로 하려면 할 말을 함께 알린다', () => {
    expect(formatHeldWrite('휴가를 기록', '휴가 등록해줘')).toBe(
      '질문으로 보여서 휴가를 기록하지 않았어요. 실제로 하려면 "휴가 등록해줘"처럼 말해 주세요.',
    );
  });
});

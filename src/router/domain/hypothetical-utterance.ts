// 자연어 쓰기 가드 — 질문·가정형 문장이 승인 게이트 없는 쓰기(휴가 등록·취소, 지원 추가·
// 상태 변경, 일정 등록)로 실행되지 않게 막는다.
//
// "총 8개를 선입 받았다고 가정했을 때 남은 휴가" 같은 문장이 파서에서 REGISTER 로 뭉개지면
// 실제로 기록된다(2026-10-07 점검). 파서 프롬프트만 고치면 회차마다 달라지므로 쓰기 직전에
// 코드가 한 번 더 본다.
//
// 표지는 질문·가정으로 좁혀 둔다. `하면`·`쓰면` 같은 조건 어미 단독은 "면접 보면 상태 바꿔줘"
// 같은 평서 지시까지 막으므로 넣지 않는다. 대신 끝의 `?` 는 넣는다 — "내일 휴가 등록해줄래?"
// 도 막히지만, 막힌 쪽은 재요청 한 번으로 끝나고 잘못 기록된 쪽은 사용자가 모를 수 있다.
//
// 슬래시 명령·콘솔 버튼은 명시 입력이라 이 가드를 타지 않는다 — 자연어 dispatcher 만 부른다.
export const HYPOTHETICAL_MARKERS: readonly RegExp[] = [
  /가정/,
  /만약/,
  /라면(?=\s|[,.!?]|$)/,
  /기준이면/,
  // "쓰면 몇 일", "쓰면 남은", "지원하면 이번달 몇 개" — 조건절 뒤 짧은 거리 안의 수량 질문.
  /면\s*(?:남|[^.?!\n]{0,12}?(?:몇|며칠|얼마))/,
  /(?:남아|맞아|맞지|되나|돼)\s*[?？]/,
  /[?？]\s*$/,
];

// 원문이 질문·가정형이면 걸린 표지를, 아니면 null 을 돌려준다. 걸린 표지는 막은 사유로 남긴다.
export const findHypotheticalMarker = (text: string): string | null => {
  const found = HYPOTHETICAL_MARKERS.find((marker) => marker.test(text));
  return found ? found.source : null;
};

// 가드에 걸려 쓰기를 하지 않았을 때의 응답. what 은 "휴가를 기록" 처럼 하지 않은 일,
// command 는 실제로 하려면 할 말("등록해줘").
export const formatHeldWrite = (what: string, command: string): string =>
  `질문으로 보여서 ${what}하지 않았어요. 실제로 하려면 "${command}"처럼 말해 주세요.`;

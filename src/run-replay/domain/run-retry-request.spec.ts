import { parseRunRetryRequest } from './run-retry-request';

describe('parseRunRetryRequest', () => {
  it.each([
    '실행번호 14034에 대해서 다시 해봐.',
    '실행 번호 `14034` 재실행',
    '실행번호 14034 한 번 더 돌려줘',
    '실행번호 14034 다시 실행해줘',
  ])('번호와 재시도 요청 %s 를 파싱한다', (text) => {
    expect(parseRunRetryRequest(text)).toBe(14034);
  });
  it.each([
    '실행번호 14034 다시 하지 마',
    '실행번호 14034 다시 안 해줘',
    '실행번호 14034 다시 해주지 마',
    '실행번호 14034 이랑 실행번호 14035 다시 해줘',
    '실행번호 14034 다시 돌리는 방법 알려줘',
    '실행번호 14034 왜 다시 실패했어?',
    '실행번호 14034 결과 보여줘',
    '실행번호 14034 결과 다시 보여줘',
    '실행번호 14034 다시 실행하지 말고 결과만 알려줘',
    '실행번호 14034 다시',
    '다시 해봐',
    '<https://x?a=1> 실행번호 다시',
    '실행번호 0 다시',
  ])('번호나 재시도 요청이 없으면 %s 를 거절한다', (text) => {
    expect(parseRunRetryRequest(text)).toBeNull();
  });
});
